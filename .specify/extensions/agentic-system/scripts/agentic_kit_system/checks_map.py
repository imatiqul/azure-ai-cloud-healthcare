@check("CK-MAP-SCHEMA", ("MAP-1", "MAP-2", "MAP-3"), "the system map is well formed", profiles=SYS)
def ck_map_schema(ctx: Context, res: Result) -> None:
    smap = load_map(ctx)
    if smap.raw.get("schema") != "agentic-map/1":
        res.fail("schema must be agentic-map/1", MAP_PATH)
    seen = set()
    for n in smap.raw.get("nodes") or []:
        nid = n.get("id") if isinstance(n, dict) else None
        if not nid:
            res.fail("a node has no id", MAP_PATH)
            continue
        if nid in seen:
            res.fail(f"node {nid} is defined twice", MAP_PATH)
        seen.add(nid)
        if n.get("type") not in NODE_TYPES:
            res.fail(f"node {nid} has unknown type {n.get('type')!r}", MAP_PATH)
        if n.get("origin") not in ("derived", "assumed"):
            res.fail(f"node {nid} must say whether it is derived or assumed", MAP_PATH)
    for e in smap.edges:
        label = f"{e.get('from')} {e.get('rel')} {e.get('to')}"
        if e.get("rel") not in EDGE_TYPES:
            res.fail(f"edge {label} has an unknown relation", MAP_PATH)
        for end in ("from", "to"):
            if e.get(end) not in smap.nodes:
                res.fail(f"edge {label} points at {e.get(end)!r}, which is not a node", MAP_PATH)
        if e.get("origin") not in ("derived", "assumed"):
            res.fail(f"edge {label} must say whether it is derived or assumed", MAP_PATH)
    for entry in smap.raw.get("index") or []:
        if entry.get("node") not in smap.nodes:
            res.fail(f"index entry points at {entry.get('node')!r}, which is not a node", MAP_PATH)


@check("CK-MAP-OWNER", ("MAP-4",), "every node has an owner, a tier and a classification", profiles=SYS)
def ck_map_owner(ctx: Context, res: Result) -> None:
    smap = load_map(ctx)
    roles = set((ctx.roles().get("roles") or {}).keys())
    for nid, n in smap.nodes.items():
        if not n.get("owner"):
            res.fail(f"node {nid} has no owner", MAP_PATH)
        elif n["owner"] not in roles:
            res.fail(f"node {nid} is owned by {n['owner']}, which is not a defined role", MAP_PATH)
        if n.get("tier") not in TIERS:
            res.fail(f"node {nid} has no valid tier", MAP_PATH)
        if not n.get("classification"):
            res.fail(f"node {nid} has no data classification", MAP_PATH)


def _evidence_path(value) -> str:
    return re.split(r"[:;(\s]", str(value).strip(), maxsplit=1)[0] if value else ""


@check("CK-MAP-EVIDENCE", ("MAP-5", "ADP-9"), "every derived fact in the map cites a file that exists", profiles=SYS)
def ck_map_evidence(ctx: Context, res: Result) -> None:
    smap = load_map(ctx)
    assumed = 0
    for kind, items in (("node", smap.nodes.values()), ("edge", smap.edges)):
        for item in items:
            label = item.get("id") or f"{item.get('from')} {item.get('rel')} {item.get('to')}"
            if item.get("origin") == "assumed":
                assumed += 1
                continue
            path = _evidence_path(item.get("evidence"))
            if not path:
                res.fail(f"derived {kind} {label} cites no evidence", MAP_PATH)
            elif not ctx.src.exists(path) and not ctx.src.files(path.rstrip("/")):
                res.fail(f"derived {kind} {label} cites {path}, which does not exist", MAP_PATH)
    if assumed:
        res.notes.append(f"{assumed} map entr{'y is' if assumed == 1 else 'ies are'} assumed and still need a human to confirm")


@check("CK-MAP-DRIFT", ("MAP-6", "TRC-9"), "the map matches what discovery finds in the code", profiles=SYS)
def ck_map_drift(ctx: Context, res: Result) -> None:
    import fnmatch
    smap = load_map(ctx)
    found = disc.discover(ctx)
    ignore = ((smap.raw.get("discovery") or {}).get("ignore")) or []
    known = set(smap.nodes)
    alias = {}
    for nid, n in smap.nodes.items():
        for a in n.get("aliases") or []:
            alias[a] = nid
    resolve = lambda i: i if i in known else alias.get(i)  # noqa: E731
    discovered_ids = set()
    for n in found["nodes"]:
        if any(fnmatch.fnmatch(n["id"], g) for g in ignore):
            continue
        target = resolve(n["id"])
        if target is None:
            res.fail(f"{n['type']} {n['id']} exists in the code but not in the map", n["evidence"])
        else:
            discovered_ids.add(target)
    have = {(e.get("from"), e.get("rel"), e.get("to")) for e in smap.edges}
    for e in found["edges"]:
        a, b = resolve(e["from"]), resolve(e["to"])
        if a and b and (a, e["rel"], b) not in have:
            res.fail(f"{a} {e['rel']} {b} exists in the code but not in the map", e["evidence"])
    for nid, n in smap.nodes.items():
        if n.get("discovered_by") and nid not in discovered_ids:
            res.fail(f"node {nid} is in the map as discovered by {n['discovered_by']}, but discovery no longer finds it", MAP_PATH)


@check("CK-MAP-FEDERATION", ("MAP-7",), "maps federated from other repositories are pinned and readable", profiles=SYS)
def ck_map_federation(ctx: Context, res: Result) -> None:
    smap = load_map(ctx)
    for f in smap.raw.get("federated") or []:
        name = f.get("name") or str(f.get("repo", "")).replace("/", "-")
        ref = str(f.get("ref", ""))
        if not f.get("repo"):
            res.fail("a federated map names no repository", MAP_PATH)
        if not _SHA.fullmatch(ref):
            res.fail(f"federated map {name} is pinned to {ref!r}, which is not a commit", MAP_PATH)
        snap = f"system-map/federated/{name}.yml"
        if not ctx.src.exists(snap):
            res.fail(f"federated map {name} has no snapshot at {snap}", MAP_PATH)
            continue
        data = ctx.src.yaml(snap) or {}
        if data.get("schema") != "agentic-map/1":
            res.fail("the snapshot is not a system map", snap)
        if str(data.get("ref", "")) != ref:
            res.fail(f"the snapshot was taken at {data.get('ref')!r}, not the pinned {ref}", snap)


