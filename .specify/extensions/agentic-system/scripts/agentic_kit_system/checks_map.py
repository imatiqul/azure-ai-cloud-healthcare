SYS = ("standard", "regulated")
_SHA = re.compile(r"[0-9a-f]{7,40}")


def approved_gates(ctx: Context) -> dict[str, set[str]]:
    out: dict[str, set[str]] = {}
    for _, rec in decisions(ctx):
        if rec.get("decision") in ("approve", "approve-with-conditions"):
            out.setdefault(str(rec.get("spec")), set()).add(str(rec.get("gate")))
    return out


def changed_files(ctx: Context) -> list[str] | None:
    """Files changed by the change under review: given explicitly, or the diff against the base ref."""
    if ctx.options.get("changed_files") is not None:
        return list(ctx.options["changed_files"])
    if ctx.trusted.ref:
        p = subprocess.run(["git", "-C", str(ctx.src.root), "diff", "--name-only", ctx.trusted.ref], capture_output=True, text=True)
        if p.returncode:
            raise KitError(f"git diff against {ctx.trusted.ref} failed: {p.stderr.strip()[:160]}")
        q = subprocess.run(["git", "-C", str(ctx.src.root), "ls-files", "--others", "--exclude-standard"], capture_output=True, text=True)
        return sorted({x for x in (p.stdout + q.stdout).splitlines() if x})
    return None


def touches(ctx: Context, spec: str) -> list[str]:
    return [str(t) for t in (spec_front(ctx, spec).get("touches") or [])]


# ── impact (MAP-10 to MAP-12, GOV-10) ───────────────────────────────────────────

def compute_impact(ctx: Context, smap: SystemMap, spec: str) -> dict:
    touched = [t for t in touches(ctx, spec) if t in smap.nodes]
    affected = smap.blast_radius(touched)
    tier = max((smap.nodes[t].get("tier") for t in touched), key=tier_rank, default=None)
    direct = touched + [a["node"] for a in affected if a["distance"] == 1]
    protected = restricted_classes(ctx)

    def owners(ids: list[str]) -> list[str]:
        roles = []
        for nid in ids:
            n = smap.nodes[nid]
            extra = [n.get("owner")]
            if n.get("type") in DATA_TYPES:
                extra.append("data-owner")
            if n.get("type") in SHARED_TYPES:
                extra.append("platform")
            if n.get("classification") in protected:
                extra.append("security-compliance")
            for r in extra:
                if r and r not in roles:
                    roles.append(r)
        return sorted(roles)

    packs = sorted({p for t in touched for p in (
        ["data-store"] if smap.nodes[t].get("type") in DATA_TYPES else
        ["shared-component"] if smap.nodes[t].get("type") in SHARED_TYPES else
        ["contract"] if smap.nodes[t].get("type") in CONTRACT_TYPES else
        ["external"] if smap.nodes[t].get("type") in ("external-application", "external-service") else [])})
    return {"spec": spec, "touches": sorted(touched), "affected": affected, "tier_computed": tier,
            "required_approvers": {"G3": owners(direct), "G5": owners(touched)}, "packs_triggered": packs}


def render_impact(impact: dict, smap: SystemMap) -> str:
    lines = ["---", yaml.safe_dump(impact, sort_keys=False).rstrip(), "---", f"# Impact report: {impact['spec']}", "",
             "Generated by the kit from the system map. Do not edit; regenerate with the impact command.", "",
             f"- **Touches:** {', '.join(impact['touches']) or 'nothing in the map'}",
             f"- **Tier from the map:** {impact['tier_computed'] or 'none'}",
             f"- **Change packs triggered:** {', '.join(impact['packs_triggered']) or 'none'}",
             f"- **Must approve the plan (G3):** {', '.join(impact['required_approvers']['G3']) or 'no one beyond the defaults'}",
             f"- **Must approve the implementation (G5):** {', '.join(impact['required_approvers']['G5']) or 'no one beyond the defaults'}",
             "", "## Blast radius", ""]
    if impact["affected"]:
        lines += ["| Distance | Node | Type | Owner | Reached because it |", "|---|---|---|---|---|"]
        lines += [f"| {a['distance']} | {a['node']} | {smap.nodes[a['node']].get('type', '')} | {a['owner']} | {a['via']} |"
                  for a in impact["affected"]]
    else:
        lines.append("Nothing else in the map depends on what this spec touches.")
    return "\n".join(lines) + "\n"


def role_hook(ctx: Context, spec: str, gate: str) -> list[str]:
    if gate not in ("G3", "G5") or ctx.profile not in SYS or not ctx.src.exists(f"specs/{spec}/spec.md"):
        return []
    smap = load_map(ctx, required=False)
    return compute_impact(ctx, smap, spec)["required_approvers"][gate] if smap else []


def lane_hook(ctx: Context, spec: str) -> str | None:
    """GOV-17: the fast lane is for a spec whose every touched node is Low tier and which triggers no change pack."""
    if ctx.profile not in SYS or not ctx.src.exists(f"specs/{spec}/spec.md"):
        return None
    smap = load_map(ctx, required=False)
    if smap is None:
        return None
    declared = touches(ctx, spec)
    impact = compute_impact(ctx, smap, spec)
    if not declared or sorted(declared) != impact["touches"]:  # touches nothing, or something the map does not know
        return None
    low = impact["tier_computed"] == "low" and spec_front(ctx, spec).get("tier_declared") == "low"
    return "fast" if low and not impact["packs_triggered"] else None


def artifact_hook(ctx: Context, spec: str) -> list[str]:
    """QLT-1: the files of the components a spec says it touches are part of what its verifier may read."""
    smap = load_map(ctx, required=False)
    if smap is None:
        return []
    return _paths_of(smap, set(touches(ctx, spec)))


def reading_hook(ctx: Context, spec: str) -> list[str]:
    """QLT-1: a verifier may read the files of the components a spec says it depends on. They are not part of its change."""
    smap = load_map(ctx, required=False)
    if smap is None:
        return []
    depends = (spec_front(ctx, spec).get("depends_on") or {}).get("nodes") or []
    return _paths_of(smap, {str(d) for d in depends})


def _paths_of(smap: SystemMap, nodes: set[str]) -> list[str]:
    return [glob for entry in smap.raw.get("index") or [] if entry.get("node") in nodes for glob in entry.get("paths") or []]


#: How the `why` trace names what a change reaches, in the order it lists them.
REACH_KINDS = [("data stores", DATA_TYPES | {"event-stream"}), ("contracts and events", CONTRACT_TYPES),
               ("shared components", SHARED_TYPES), ("external systems", {"external-application", "external-service"})]


def why_hook(ctx: Context, path: str, spec: str) -> list[str]:
    """TRC-19, forward: the component a file belongs to, and everything the spec's change reaches, by kind."""
    smap = load_map(ctx, required=False)
    if smap is None:
        return []
    lines = []
    node = smap.node_for(path)
    if node and node in smap.nodes:
        n = smap.nodes[node]
        lines.append(f"- **Component:** `{node}` ({n.get('type')}, owner {n.get('owner') or 'not named'}, tier {n.get('tier') or 'not set'})")
    impact = compute_impact(ctx, smap, spec)
    reached = impact["touches"] + [a["node"] for a in impact["affected"]]
    if not reached:
        return lines
    lines.append(f"- **The spec touches:** {', '.join(f'`{t}`' for t in impact['touches'])}")
    depends = [str(d) for d in (spec_front(ctx, spec).get("depends_on") or {}).get("nodes") or [] if str(d) in smap.nodes]
    if depends:
        lines.append("- **The spec depends on:** " + ", ".join(f"`{d}` ({smap.nodes[d].get('type')})" for d in depends))
    rest = [r for r in reached if r not in impact["touches"] and r not in depends]
    named: set[str] = set()
    for label, types in REACH_KINDS:
        found = sorted(r for r in rest if smap.nodes[r].get("type") in types)
        named.update(found)
        if found:
            lines.append(f"- **Reaches {label} ({len(found)}):** {', '.join(f'`{r}`' for r in found)}")
    other = sorted(r for r in rest if r not in named)
    if other:
        lines.append(f"- **Reaches applications and other components ({len(other)}):** {', '.join(f'`{r}`' for r in other)}")
    return lines


def brief_hook(ctx: Context, spec: str, gate: str) -> list[tuple[str, list[str]]]:
    smap = load_map(ctx, required=False)
    if smap is None or ctx.profile not in SYS:
        return []
    impact = compute_impact(ctx, smap, spec)
    near = [a for a in impact["affected"] if a["distance"] == 1]
    lines = [f"- Touches: {', '.join(impact['touches']) or 'nothing in the system map'}",
             f"- Tier from the map: {impact['tier_computed'] or 'none'}. Change packs: {', '.join(impact['packs_triggered']) or 'none'}",
             f"- Reaches {len(impact['affected'])} other node(s), {len(near)} directly"
             + (": " + ", ".join(a["node"] for a in near[:6]) + (" and more" if len(near) > 6 else "") if near else "")]
    risks = []
    protected = restricted_classes(ctx)
    hit = [t for t in impact["touches"] if smap.nodes[t].get("classification") in protected]
    if hit:
        risks.append(f"- Touches protected data: {', '.join(hit)}")
    critical = [t for t in impact["touches"] if smap.nodes[t].get("tier") == "critical"]
    if critical:
        risks.append(f"- Touches Critical-tier nodes: {', '.join(critical)}")
    assumed = [t for t in impact["touches"] if smap.nodes[t].get("origin") == "assumed"]
    if assumed:
        risks.append(f"- Relies on map entries nobody has confirmed: {', '.join(assumed)}")
    plan = f"specs/{spec}/data-change-plan.md"
    if ctx.src.exists(plan):
        cls = front_matter(ctx.src.read(plan)).get("classification")
        if cls in ("breaking", "destructive"):
            risks.append(f"- The data change is declared {cls}")
    return [("Impact", lines), ("Risks", risks)]


def manifest_hook(ctx: Context, spec: str, manifest: dict) -> None:
    """TRC-2: requirements link to the system-map nodes their spec touches."""
    smap = load_map(ctx, required=False)
    if smap is None:
        return
    declared = touches(ctx, spec)
    for row in manifest["rows"]:
        row["nodes"] = sorted(t for t in declared if t in smap.nodes)
    for t in declared:
        if t not in smap.nodes:
            manifest["gate"]["failures"].append(f"{t}: spec touches a node that is not in the system map")
    manifest["gate"]["failures"] = sorted(set(manifest["gate"]["failures"]))


