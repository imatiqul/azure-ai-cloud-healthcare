@check("CK-TOUCH", ("MAP-8", "MAP-9"), "a change only modifies nodes its spec declares", profiles=SYS)
def ck_touch(ctx: Context, res: Result) -> None:
    smap = load_map(ctx)
    for spec in ctx.specs():
        for t in touches(ctx, spec):
            if t not in smap.nodes:
                res.fail(f"touches {t}, which is not in the system map", f"specs/{spec}/spec.md")
    changed = changed_files(ctx)
    if changed is None:
        res.notes.append("skipped the file comparison: no base ref or list of changed files was given")
        return
    done = approved_gates(ctx)
    active = [s for s in ctx.specs() if any(c.startswith(f"specs/{s}/") for c in changed)] or \
             [s for s in ctx.specs() if "G5" not in done.get(s, set())]
    declared = {t for s in active for t in touches(ctx, s)}
    unmapped = 0
    for c in changed:
        if c.startswith(("specs/", ".specify/", "system-map/", ".github/")):
            continue
        node = smap.node_for(c)
        if node is None:
            unmapped += 1
        elif node not in declared:
            res.fail(f"{c} belongs to {node}, which no spec in this change declares in `touches`", c)
    if unmapped:
        res.notes.append(f"{unmapped} changed file(s) are not indexed to any node in the map")


@check("CK-IMPACT", ("MAP-10", "MAP-11", "MAP-12"), "each planned spec has a current impact report", profiles=SYS)
def ck_impact(ctx: Context, res: Result) -> None:
    smap = load_map(ctx)
    for spec in ctx.specs():
        if not ctx.src.exists(f"specs/{spec}/plan.md"):
            continue
        rel = f"specs/{spec}/impact.md"
        if not ctx.src.exists(rel):
            res.fail("plan.md exists but the impact report has not been generated", rel)
            continue
        if front_matter(ctx.src.read(rel)) != compute_impact(ctx, smap, spec):
            res.fail("the impact report is out of date with the spec or the map; regenerate it", rel)


@check("CK-TIER-RAISE", ("GOV-10", "MAP-12"), "a spec's tier is at least the highest tier it touches", profiles=SYS)
def ck_tier_raise(ctx: Context, res: Result) -> None:
    smap = load_map(ctx)
    for spec in ctx.specs():
        declared = spec_front(ctx, spec).get("tier_declared")
        for t in touches(ctx, spec):
            node_tier = (smap.nodes.get(t) or {}).get("tier")
            if tier_rank(node_tier) > tier_rank(declared):
                res.fail(f"declared {declared} but touches {t}, which is {node_tier}", f"specs/{spec}/spec.md")


@check("CK-CROSS-SPEC", ("MAP-13",), "specs that share a node are ordered, and dependencies pass their gates first", profiles=SYS)
def ck_cross_spec(ctx: Context, res: Result) -> None:
    done = approved_gates(ctx)
    specs = ctx.specs()
    deps = {s: [str(d) for d in ((spec_front(ctx, s).get("depends_on") or {}).get("specs") or [])] for s in specs}
    flying = [s for s in specs if "G5" not in done.get(s, set())]
    for i, a in enumerate(flying):
        for b in flying[i + 1:]:
            shared = sorted(set(touches(ctx, a)) & set(touches(ctx, b)))
            if shared and b not in deps[a] and a not in deps[b]:
                res.fail(f"{a} and {b} both touch {', '.join(shared)} and neither depends on the other", f"specs/{a}/spec.md")
    for a in specs:
        for b in deps[a]:
            if b not in specs:
                res.fail(f"depends on spec {b}, which does not exist", f"specs/{a}/spec.md")
                continue
            for gate in sorted(done.get(a, set())):
                if gate not in done.get(b, set()):
                    res.fail(f"{gate} is approved but {b}, which this spec depends on, has not passed {gate}", f"specs/{a}/spec.md")


@check("CK-PROGRAMME", ("MAP-14",), "a programme spec names its children, the shared contract and the rollout order", profiles=SYS)
def ck_programme(ctx: Context, res: Result) -> None:
    smap = load_map(ctx)
    for spec in ctx.specs():
        prog = spec_front(ctx, spec).get("programme")
        if not prog:
            continue
        rel = f"specs/{spec}/spec.md"
        children = prog.get("children") or []
        if not children:
            res.fail("a programme spec has no children", rel)
        names = []
        for c in children:
            name = str(c.get("spec", ""))
            names.append(name)
            repo = c.get("repo", ".")
            if repo == ".":
                if not ctx.src.exists(f"specs/{name}/spec.md"):
                    res.fail(f"child spec {name} does not exist", rel)
                elif spec_front(ctx, name).get("parent") != spec:
                    res.fail(f"child spec {name} does not name {spec} as its parent", f"specs/{name}/spec.md")
            elif not _SHA.fullmatch(str(c.get("ref", ""))):
                res.fail(f"child spec {name} in {repo} is not pinned to a commit", rel)
        contract = prog.get("contract")
        if not contract:
            res.fail("a programme spec names no shared contract", rel)
        elif (smap.nodes.get(contract) or {}).get("type") not in CONTRACT_TYPES:
            res.fail(f"shared contract {contract} is not a contract or event in the system map", rel)
        rollout = [str(x) for x in prog.get("rollout") or []]
        for name in names:
            if name not in rollout:
                res.fail(f"the rollout order does not include child {name}", rel)


@check("CK-FINDING-EVIDENCE", ("MAP-15",), "every finding from brownfield discovery cites evidence that exists", profiles=SYS)
def ck_finding_evidence(ctx: Context, res: Result) -> None:
    rel = f"{KIT_DIR}/findings.yml"
    if not ctx.src.exists(rel):
        return
    for f in (ctx.src.yaml(rel) or {}).get("findings") or []:
        fid = f.get("id", "?")
        if not f.get("statement"):
            res.fail(f"finding {fid} has no statement", rel)
        evidence = f.get("evidence") or []
        if not evidence:
            res.fail(f"finding {fid} cites no evidence", rel)
        for item in evidence:
            path = _evidence_path(item)
            if not ctx.src.exists(path) and not ctx.src.files(path.rstrip("/")):
                res.fail(f"finding {fid} cites {path}, which does not exist", rel)
