"""Lanes, amendments and the reviewer brief (GOV-12, GOV-17 to GOV-20).

* Fast lane: a Low-tier change may have G1 to G3 folded into G4. Impact analysis selects the lane.
* Emergency lane: one human approval now, a retrospective spec through every gate by a deadline.
* Amendments: a change to something already approved re-opens the gates that approved it, and only those.
* Brief: one page for the person at the gate, generated and bound into the gate's evidence.
"""
from __future__ import annotations

import datetime
import re
import subprocess

import yaml

from . import adapters
from .checks_gov import (FAST_MERGED, _approver_problems, _commit, _has_commit, _review, active_waivers, as_date, decisions,
                         gate_roles, lane, people_by_role, required_gates, spec_front, today)
from .core import GATES, KIT_DIR, Context, KitError, Result, Source, check, evidence_hash, front_matter

SYS = ("standard", "regulated")
EMERGENCIES = f"{KIT_DIR}/emergencies"
EMERGENCY_ROLES = ["devops-sre", "engineering-manager", "security-compliance"]
CONSTITUTION = ".specify/memory/constitution.md"
CONSTITUTION_MAP = f"{KIT_DIR}/constitution.map.yml"
BRIEF_MARK = "Generated by agentic-spec-kit: reviewer brief"
BRIEF_LINES = 80
#: What each gate approved that a later edit can amend. Generated and progress files are left out on purpose.
AMENDABLE = {"G1": ["spec.md"], "G2": ["spec.md"], "G3": ["plan.md", "impact.md", "data-change-plan.md", "rollout.yml"], "G4": ["tasks.md"]}


def approved_records(ctx: Context, spec: str) -> dict[str, tuple[str, dict]]:
    out = {}
    for rel, rec in decisions(ctx):
        if str(rec.get("spec")) == spec and rec.get("decision") in ("approve", "approve-with-conditions"):
            out[str(rec.get("gate"))] = (rel, rec)
    return out


def complete(ctx: Context, spec: str) -> bool:
    """Has the spec an approving decision for every gate its profile and lane require?"""
    return ctx.src.exists(f"specs/{spec}/spec.md") and set(required_gates(ctx, spec)) <= set(approved_records(ctx, spec))


# ── GOV-17: the fast lane ───────────────────────────────────────────────────────

@check("CK-LANE", ("GOV-17",), "a spec is on the fast lane only when impact analysis puts it there", profiles=SYS)
def ck_lane(ctx: Context, res: Result) -> None:
    for spec in ctx.specs():
        computed = lane(ctx, spec)
        declared = spec_front(ctx, spec).get("lane")
        if declared is not None and declared != computed:
            res.fail(f"the spec says lane {declared}, but impact analysis computes {computed}; the lane is not the author's to choose",
                     f"specs/{spec}/spec.md")
        for gate, (rel, rec) in approved_records(ctx, spec).items():
            if rec.get("lane") == "fast" and computed != "fast":
                res.fail(f"{gate} was approved on the fast lane, but the spec no longer qualifies; G1 to G3 need their own decisions", rel)
            if computed == "fast" and gate in FAST_MERGED:
                res.notes.append(f"{spec}: {gate} has its own decision although the fast lane folds it into G4")


# ── GOV-18: the emergency lane ──────────────────────────────────────────────────

def emergencies(ctx: Context) -> list[tuple[str, dict]]:
    out = []
    for rel in ctx.src.files(EMERGENCIES):
        if rel.endswith(".yml"):
            body = ctx.src.yaml(rel)
            out.append((rel, body if isinstance(body, dict) else {}))
    return out


def emergency_paths(ctx: Context) -> list[str]:
    """Paths covered by an emergency that is still open: changes there are expected before their spec exists."""
    return [str(p) for _, e in emergencies(ctx) if e.get("status") == "open" for p in e.get("paths") or []]


def retrospective_specs(ctx: Context) -> set[str]:
    """Specs an open emergency names as its retrospective: the change is merged first and their gates follow, by a date."""
    retros = [e.get("retrospective") for _, e in emergencies(ctx) if e.get("status") == "open"]
    return {str(r["spec"]) for r in retros if isinstance(r, dict) and r.get("spec")}


@check("CK-EMERGENCY-DEADLINE", ("GOV-18",), "an emergency change has one valid human approval and its retrospective is done by the deadline")
def ck_emergency_deadline(ctx: Context, res: Result) -> None:
    found = emergencies(ctx)
    if not found:
        return
    cfg = (ctx.kit().get("lanes") or {}).get("emergency") or {}
    days = cfg.get("days")
    if not isinstance(days, int) or days < 1:
        res.fail("there are emergency records but kit.yml sets no deadline (lanes.emergency.days)", f"{KIT_DIR}/kit.yml")
        return
    allowed = list(cfg.get("roles") or EMERGENCY_ROLES)
    adapter = adapters.enforcement(ctx)
    holders = people_by_role(ctx.roles())
    now = today(ctx)
    for rel, e in found:
        eid = e.get("id") or rel.rsplit("/", 1)[-1][:-4]
        if e.get("schema") != "agentic-emergency/1":
            res.fail("schema must be agentic-emergency/1", rel)
        for key in ("summary", "commit", "paths"):
            if not e.get(key):
                res.fail(f"emergency {eid} has no {key}", rel)
        ap = e.get("declared_by") or {}
        change, review = _review(adapter, ap.get("review_ref"))
        if review is None:
            res.fail(f"emergency {eid}: review {ap.get('review_ref')!r} was not found in the enforcement channel", rel)
        else:
            problems = _approver_problems(ctx, adapter, holders, review, change, ap.get("reviewer", ""), ap.get("role"))
            if review.state != "APPROVED":
                problems.append(f"the review state is {review.state or 'unknown'}, not APPROVED")
            if ap.get("role") not in allowed:
                problems.append(f"role {ap.get('role')} may not declare an emergency (allowed: {', '.join(allowed)})")
            for p in problems:
                res.fail(f"emergency {eid}: {p}", rel)
        declared = as_date(e.get("declared"))
        if declared is None:
            res.fail(f"emergency {eid} has no declared date", rel)
            continue
        due = declared + datetime.timedelta(days=days)
        retro = e.get("retrospective") or {}
        stated = as_date(retro.get("due"))
        if stated is not None and stated > due:
            res.fail(f"emergency {eid} gives itself until {stated}, later than the {days} days kit.yml allows ({due})", rel)
        spec = str(retro.get("spec") or "")
        done = bool(spec) and complete(ctx, spec)
        if e.get("status") == "closed":
            if not done:
                res.fail(f"emergency {eid} is closed, but its retrospective spec {spec or '(none)'} has not passed every gate", rel)
        elif e.get("status") != "open":
            res.fail(f"emergency {eid} status must be open or closed", rel)
        elif done:
            res.notes.append(f"emergency {eid}: the retrospective is complete; the record can be closed")
        elif now > due:
            res.fail(f"emergency {eid} was due on {due}: retrospective spec {spec or '(none named)'} has not passed every gate", rel)
        else:
            res.notes.append(f"emergency {eid}: retrospective due {due} ({(due - now).days} day(s) left)")


# ── GOV-19 and GOV-12: amendments ───────────────────────────────────────────────

def _sections(text: str) -> dict[str, str]:
    out: dict[str, str] = {"": ""}
    current = ""
    for line in re.sub(r"\A---\s*\n.*?\n---\s*\n", "", text, flags=re.S).splitlines():
        m = re.match(r"#{1,6}\s+(.*?)\s*#*\s*$", line)
        if m:
            current = m.group(1).strip()
            out.setdefault(current, "")
        else:
            out[current] += line.rstrip() + "\n"
    return {k: v.strip() for k, v in out.items()}


def _parts(rel: str, text: str, gate: str) -> dict[str, str]:
    """The pieces of a file that a gate approved, in a form that ignores progress marks and layout."""
    name = rel.rsplit("/", 1)[-1]
    if name == "tasks.md":
        return {"task list": re.sub(r"\[[xX ]\]", "[ ]", "\n".join(x.rstrip() for x in text.splitlines())).strip()}
    if name == "spec.md":
        parts = {f"section '{k or 'introduction'}'": v for k, v in _sections(text).items()}
        parts["front matter"] = yaml.safe_dump(front_matter(text), sort_keys=True)
        if gate == "G1":  # clarifications are G2's business
            parts = {k: v for k, v in parts.items() if "clarification" not in k.lower()}
        return parts
    if name.endswith(".md"):
        parts = {f"section '{k or 'introduction'}'": v for k, v in _sections(text).items()}
        parts["front matter"] = yaml.safe_dump(front_matter(text), sort_keys=True)
        return parts
    return {"content": "\n".join(x.rstrip() for x in text.splitlines()).strip()}


def _approved_source(ctx: Context, rec: dict):
    """A reader for the tree a decision was made on: the commit, or files handed in for a test; None when unknown."""
    commit = _commit(rec)
    if commit and _has_commit(ctx, commit):
        return ctx.src.at(commit)
    given = ctx.options.get("approved_files")
    if given is not None:
        class Given:
            def exists(self, rel):
                return rel in given

            def read(self, rel):
                return given[rel]
        return Given()
    return None


def reopened(ctx: Context, spec: str) -> tuple[dict[str, list[str]], bool]:
    """gate -> what changed since it was approved; and whether every approved gate could be compared."""
    out: dict[str, list[str]] = {}
    comparable = True
    for gate, (_, rec) in sorted(approved_records(ctx, spec).items()):
        names = list(AMENDABLE.get(gate, []))
        if gate == "G4" and rec.get("lane") == "fast":
            names += [n for g in FAST_MERGED for n in AMENDABLE[g] if n not in names]
        if not names:
            continue
        before = _approved_source(ctx, rec)
        if before is None:
            comparable = False
            continue
        given_only = ctx.options.get("approved_files") is not None and not (_commit(rec) and _has_commit(ctx, _commit(rec)))
        for name in names:
            rel = f"specs/{spec}/{name}"
            had, has = before.exists(rel), ctx.src.exists(rel)
            if given_only and not had:
                continue  # a test hands in only the files it wants compared
            if had and not has:
                out.setdefault(gate, []).append(f"{name} was removed")
            elif has and not had:
                out.setdefault(gate, []).append(f"{name} was added")
            elif had and has:
                a, b = _parts(rel, before.read(rel), gate), _parts(rel, ctx.src.read(rel), gate)
                changed = sorted(k for k in set(a) | set(b) if a.get(k) != b.get(k))
                if changed:
                    out.setdefault(gate, []).append(f"{name}: {', '.join(changed[:4])}{' and more' if len(changed) > 4 else ''}")
    return out, comparable


def principles(text: str) -> dict[str, str]:
    """Principle id -> its text, from headings such as `### P-3 Title`."""
    out: dict[str, str] = {}
    current = None
    for line in text.splitlines():
        m = re.match(r"#{1,6}\s+(P-[0-9]+)\b(.*)$", line)
        if m:
            current = m.group(1)
            out[current] = m.group(2).strip() + "\n"
        elif re.match(r"#{1,6}\s", line):
            current = None
        elif current:
            out[current] += line.rstrip() + "\n"
    return {k: v.strip() for k, v in out.items()}


def amendment_report(ctx: Context) -> tuple[str, str]:
    """(path, text) of the report for the constitution as it now stands against the version approved at G0."""
    rec = approved_records(ctx, "_constitution").get("G0")
    if rec is None:
        raise KitError("the constitution has no G0 decision to amend")
    before = _approved_source(ctx, rec[1])
    if before is None:
        raise KitError("the commit of the G0 decision is not in this repository, so the approved constitution cannot be read")
    old, new = principles(before.read(CONSTITUTION)), principles(ctx.src.read(CONSTITUTION))
    old_map = {str(p.get("id")): p for p in (yaml.safe_load(before.read(CONSTITUTION_MAP)) or {}).get("principles") or []}
    now_map = ctx.src.yaml(CONSTITUTION_MAP) or {}
    new_map = {str(p.get("id")): p for p in now_map.get("principles") or []}
    changed = sorted(p for p in set(old) & set(new) if old[p] != new[p] or old_map.get(p) != new_map.get(p))
    removed, added = sorted(set(old) - set(new)), sorted(set(new) - set(old))
    hit = set(changed) | set(removed)
    invalidated = []
    for spec in ctx.specs():
        used = sorted(hit & {str(p) for p in spec_front(ctx, spec).get("principles") or []})
        gates = sorted(approved_records(ctx, spec))
        if used and gates:
            invalidated.append({"spec": spec, "principles": used, "approved_gates": gates})
    version = now_map.get("version")
    front = {"version": version, "from_version": rec[1].get("constitution_version"), "from_commit": _commit(rec[1]),
             "changed": changed, "removed": removed, "added": added, "invalidated_specs": invalidated}
    lines = ["---", yaml.safe_dump(front, sort_keys=False).rstrip(), "---", f"# Constitution amendment, version {version}", "",
             "Generated by the kit. It lists every approved spec that relied on a principle this amendment changes or removes.",
             "The people at G0 decide which of them must be reviewed again.", "",
             f"- **Changed:** {', '.join(changed) or 'none'}", f"- **Removed:** {', '.join(removed) or 'none'}", f"- **Added:** {', '.join(added) or 'none'}",
             "", "## Approved specs this invalidates", ""]
    lines += [f"- `{i['spec']}` relies on {', '.join(i['principles'])}; approved at {', '.join(i['approved_gates'])}" for i in invalidated] \
        or ["No approved spec relies on a changed or removed principle."]
    return f"{KIT_DIR}/constitution/amendment-v{version}.md", "\n".join(lines) + "\n"


@check("CK-AMENDMENT", ("GOV-12", "GOV-19"), "a change to something approved re-opens the gates that approved it", profiles=SYS)
def ck_amendment(ctx: Context, res: Result) -> None:
    unknown = 0
    for spec in ctx.specs():
        gates, comparable = reopened(ctx, spec)
        unknown += 0 if comparable else 1
        for gate, why in sorted(gates.items()):
            rel, rec = approved_records(ctx, spec)[gate]
            res.fail(f"{gate} was approved at {_commit(rec) or '?'} for an earlier version ({'; '.join(why)}); "
                     "it is re-opened and needs a new decision", rel)
    if unknown:
        res.notes.append(f"{unknown} spec(s) could not be compared with what was approved: the decision commits are not in this repository")
    g0 = approved_records(ctx, "_constitution").get("G0")
    if g0 is None:
        return
    rel, rec = g0
    cmap = ctx.src.yaml(CONSTITUTION_MAP) if ctx.src.exists(CONSTITUTION_MAP) else {}
    version = (cmap or {}).get("version")
    if not isinstance(version, int) or version < 1:
        res.fail("the constitution was approved at G0, so its map must carry a whole-number `version`", CONSTITUTION_MAP)
        return
    if rec.get("constitution_version") != version:
        res.fail(f"the constitution is at version {version}, but G0 approved version {rec.get('constitution_version')}", rel)
    before = _approved_source(ctx, rec)
    if before is not None:
        for f in (CONSTITUTION, CONSTITUTION_MAP):
            if before.exists(f) and ctx.src.exists(f) and before.read(f).strip() != ctx.src.read(f).strip():
                res.fail(f"{f} changed since G0 approved it at {_commit(rec)}; raise the version, write the amendment report and re-approve at G0", f)
    if version > 1:
        report = f"{KIT_DIR}/constitution/amendment-v{version}.md"
        if not ctx.src.exists(report):
            res.fail(f"version {version} of the constitution has no amendment report listing the specs it invalidates", report)
        elif report not in ((rec.get("evidence") or {}).get("files") or []):
            res.fail("the amendment report was not part of the evidence approved at G0", rel)


# ── GOV-20: the reviewer brief ──────────────────────────────────────────────────

def brief_path(spec: str, gate: str) -> str:
    return f"specs/{spec}/briefs/{gate}.md"


def _other_evidence(ctx: Context, spec: str, gate: str) -> list[str]:
    from . import __main__ as cli
    return [f for f in cli._evidence_files(ctx, spec, gate, None) if f != brief_path(spec, gate)]


def _cap(items: list[str], limit: int = 6) -> list[str]:
    return items[:limit] + ([f"- and {len(items) - limit} more"] if len(items) > limit else [])


def _since_last_review(ctx: Context, spec: str, gate: str, files: list[str]) -> list[str]:
    records = approved_records(ctx, spec)
    previous = [g for g in GATES if g in records and (g == gate or GATES.index(g) < GATES.index(gate))]
    if not previous:
        return ["This is the first review of this spec."] + _cap([f"- `{f}`" for f in files])
    last = previous[-1]
    commit = _commit(records[last][1])
    if not commit or not _has_commit(ctx, commit):
        return [f"The last decision was {last}; its commit is not in this repository, so the changes since cannot be listed."]
    p = subprocess.run(["git", "-C", str(ctx.src.root), "diff", "--name-only", commit, "--", f"specs/{spec}"], capture_output=True, text=True)
    q = subprocess.run(["git", "-C", str(ctx.src.root), "ls-files", "--others", "--exclude-standard", "--", f"specs/{spec}"], capture_output=True, text=True)
    # The page of the change is generated and is no part of a review: listing it would change the brief, and so the evidence (CHS-9).
    changed = sorted({x for x in (p.stdout + q.stdout).splitlines() if x and "/briefs/" not in x and not x.endswith(f"specs/{spec}/changeset.md")})
    out = [f"Since {last} was approved at `{commit[:10]}`:"]
    before = Source(ctx.src.root, commit)
    for rel in changed:
        if rel.endswith(".md") and before.exists(rel) and ctx.src.exists(rel):
            a, b = _parts(rel, before.read(rel), gate), _parts(rel, ctx.src.read(rel), gate)
            what = sorted(k for k in set(a) | set(b) if a.get(k) != b.get(k))
            out.append(f"- `{rel}` changed: {', '.join(what[:3]) or 'layout only'}")
        else:
            out.append(f"- `{rel}` {'changed' if before.exists(rel) else 'is new'}")
    return _cap(out, 9) if changed else out + ["- nothing under this spec changed"]


def build_brief(ctx: Context, spec: str, gate: str, files: list[str] | None = None) -> str:
    """The brief for a gate. `files` is the rest of the gate's evidence; by default, what the gate command would bind."""
    from .core import BRIEF_HOOKS
    files = [f for f in files if f != brief_path(spec, gate)] if files is not None else _other_evidence(ctx, spec, gate)
    if not files:
        raise KitError(f"no evidence files found for {gate} of {spec}")
    digest = evidence_hash(ctx.src, spec, gate, files)
    front = spec_front(ctx, spec)
    lines = [f"<!-- {BRIEF_MARK}. evidence: {digest} Do not edit; regenerate with the brief command. -->",
             f"# Brief for {gate} of {spec}", "",
             f"- **Decision asked for:** approve, reject, or approve with conditions, from {', '.join(gate_roles(ctx, gate, spec))}",
             f"- **Tier declared:** {front.get('tier_declared', 'none')}. **Lane:** {lane(ctx, spec)}. **Owner role:** {front.get('owner_role', 'none')}",
             "", "## What changed since the last review"] + _since_last_review(ctx, spec, gate, files)
    extra: list[tuple[str, list[str]]] = []
    for hook in BRIEF_HOOKS:
        extra += hook(ctx, spec, gate)
    for title in ("Impact", "Risks"):
        body = [line for t, ls in extra if t == title for line in ls]
        if title == "Risks":
            open_now = [e.get("id") for _, e in emergencies(ctx) if e.get("status") == "open"]
            if open_now:
                body.append(f"- Open emergency change(s): {', '.join(str(x) for x in open_now)}")
            if front.get("breaking"):
                body.append(f"- The spec declares a breaking change to: {', '.join(str(x) for x in front['breaking'])}")
        lines += ["", f"## {title}"] + (_cap(body, 8) or ["- Nothing recorded by the kit. That is not the same as no " + title.lower() + "."])
    for title in dict.fromkeys(t for t, _ in extra if t not in ("Impact", "Risks", "Disputed")):  # sections a sibling extension adds
        lines += ["", f"## {title}"] + _cap([line for t, ls in extra if t == title for line in ls], 8)
    waivers, groups = active_waivers(ctx)
    wl = [f"- `{w.get('id')}` ({w.get('rule')}), owner {w.get('owner')}, expires {w.get('expires')}{', CRITICAL' if w.get('critical') else ''}" for _, w in waivers]
    wl += [f"- adoption baseline: {count} × {rule}" for rule, (count, _) in sorted(groups.items())]
    lines += ["", "## Open waivers"] + (_cap(wl, 8) or ["- None."])
    disputed = [line for t, ls in extra if t == "Disputed" for line in ls]
    lines += ["", "## Disputed by a verifier"] + (_cap(disputed, 8) or ["- Nothing was disputed."])
    lines += ["", "## To decide", f"Evidence: {len(files)} file(s) besides this brief:"] + _cap([f"- `{f}`" for f in files], 10)
    lines += ["", f"Run the gate command for the exact line to paste into your review. It binds your decision to this evidence and this brief."]
    return "\n".join(lines) + "\n"


@check("CK-BRIEF", ("GOV-20",), "every gate decision was made with a current one-page brief in its evidence", profiles=SYS)
def ck_brief(ctx: Context, res: Result) -> None:
    for rel, rec in decisions(ctx):
        spec, gate = str(rec.get("spec")), str(rec.get("gate"))
        if spec == "_constitution" or gate not in GATES or rec.get("decision") not in ("approve", "approve-with-conditions"):
            continue
        files = [str(f) for f in (rec.get("evidence") or {}).get("files") or []]
        brief = brief_path(spec, gate)
        if brief not in files:
            res.fail(f"the evidence for {gate} does not include the reviewer brief ({brief})", rel)
            continue
        commit = _commit(rec)
        source = ctx.src.at(commit) if commit and _has_commit(ctx, commit) else ctx.src
        if not source.exists(brief):
            res.fail(f"the brief {brief} does not exist at the decision's commit", rel)
            continue
        text = source.read(brief)
        m = re.search(r"evidence: (sha256:[0-9a-f]{64})", text.splitlines()[0] if text else "")
        if BRIEF_MARK not in text[:200] or not m:
            res.fail("the brief was not generated by the kit", brief)
            continue
        try:
            if evidence_hash(source, spec, gate, [f for f in files if f != brief]) != m.group(1):
                res.fail("the brief describes different evidence from what was approved; regenerate it before the review", brief)
        except KitError as exc:
            res.fail(str(exc), rel)
        if len(text.splitlines()) > BRIEF_LINES:
            res.fail(f"the brief is {len(text.splitlines())} lines; it must fit on one page ({BRIEF_LINES} lines)", brief)
