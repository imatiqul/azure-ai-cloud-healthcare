"""Living capability specs (PRD-6 to PRD-13).

One file per capability says what the system does today. A change never edits that file: it carries a delta
(added, modified, removed, renamed requirements). When the change is released, the merge command applies the delta.
CK-LIVING-SPEC replays every merged delta and compares the result with the files, so a hand edit cannot survive.
"""
from __future__ import annotations

import datetime
import json
import re
from dataclasses import dataclass, field
from pathlib import Path

import yaml

from agentic_kit.checks_gov import as_date, today
from agentic_kit.core import KIT_DIR, Context, KitError, Result, check, front_matter
from agentic_kit.lanes import complete

from . import common
from .common import INDEX, INDEX_SCHEMA, PRODUCT, sha
from .intake import decided_by_problem

CAPS = f"{PRODUCT}/capabilities"
MERGES = f"{PRODUCT}/merges"
ADOPTION = f"{PRODUCT}/adoption"
ADOPTION_ID = "_adoption"
MERGE_SCHEMA = "agentic-merge/1"
SEAL_SCHEMA = "agentic-seal/1"
SEAL = "SEALED.yml"
MARK = "Generated by agentic-spec-kit: living capability spec"
KINDS = ("ADDED", "MODIFIED", "REMOVED", "RENAMED")
AFTER_SEAL = ("release/production-checks.yml", "outcomes-review.yml")  # records that are written after a release
BEHAVIOUR_NODES = {"service", "frontend", "ai-component"}

_REQ = re.compile(r"^###\s+Requirement:\s*(.+?)\s*$", re.M)
_SCN = re.compile(r"^####\s+Scenario:\s*(.+?)\s*$", re.M)
_SECTION = re.compile(r"^##\s+(.+?)\s*$", re.M)
_FIELD = re.compile(r"^(Verifies|Reason|Sources):\s*(.*)$", re.M | re.I)
_RENAME = re.compile(r"^\s*[-*]\s*`(.+?)`\s*(?:->|→|to)\s*`(.+?)`\s*$", re.M)
_SLUG = re.compile(r"[a-z0-9]+(?:-[a-z0-9]+)*")
_REVIEW = re.compile(r"pull/[1-9][0-9]*#review-\S+")
_NORMATIVE = re.compile(r"\b(SHALL|MUST)\b")


def key(name: str) -> str:
    return " ".join(name.lower().split())


@dataclass
class Requirement:
    name: str
    body: str = ""
    scenarios: list[tuple[str, str]] = field(default_factory=list)
    verifies: list[str] = field(default_factory=list)
    reason: str = ""
    sources: list[str] = field(default_factory=list)


def parse_blocks(text: str) -> list[Requirement]:
    """The `### Requirement:` blocks of a section, each with its `#### Scenario:` blocks."""
    out = []
    heads = list(_REQ.finditer(text))
    for i, m in enumerate(heads):
        block = text[m.end(): heads[i + 1].start() if i + 1 < len(heads) else len(text)]
        scns = list(_SCN.finditer(block))
        head = block[: scns[0].start()] if scns else block
        req = Requirement(name=m.group(1))
        for f in _FIELD.finditer(head):
            name, value = f.group(1).lower(), f.group(2).strip()
            if name == "verifies":
                req.verifies = re.findall(r"FR-[0-9]{3,}", value)
            elif name == "reason":
                req.reason = value
            else:
                req.sources = [s.strip() for s in value.split(",") if s.strip()]
        req.body = "\n".join(line.rstrip() for line in _FIELD.sub("", head).strip().splitlines()).strip()
        for j, s in enumerate(scns):
            body = block[s.end(): scns[j + 1].start() if j + 1 < len(scns) else len(block)]
            req.scenarios.append((s.group(1), "\n".join(line.rstrip() for line in body.strip().splitlines())))
        out.append(req)
    return out


@dataclass
class Delta:
    rel: str
    capability: str
    front: dict
    added: list[Requirement] = field(default_factory=list)
    modified: list[Requirement] = field(default_factory=list)
    removed: list[Requirement] = field(default_factory=list)
    renamed: list[tuple[str, str]] = field(default_factory=list)
    problems: list[str] = field(default_factory=list)

    def summary(self) -> str:
        parts = [f"adds {len(self.added)}" if self.added else "", f"changes {len(self.modified)}" if self.modified else "",
                 f"removes {len(self.removed)}" if self.removed else "", f"renames {len(self.renamed)}" if self.renamed else ""]
        return ", ".join(p for p in parts if p) or "changes nothing"


def parse_delta(rel: str, text: str) -> Delta:
    front = front_matter(text)
    d = Delta(rel=rel, capability=str(front.get("capability") or rel.rsplit("/", 1)[-1][:-3]), front=front)
    if not _SLUG.fullmatch(d.capability):
        d.problems.append(f"capability id {d.capability!r} must be lower-case words joined by hyphens")
    body = common.body_of(text)
    heads = list(_SECTION.finditer(body))
    for i, m in enumerate(heads):
        title = m.group(1)
        chunk = body[m.end(): heads[i + 1].start() if i + 1 < len(heads) else len(body)]
        kind = title.split()[0].upper() if title.lower().endswith("requirements") else ""
        if kind not in KINDS:
            d.problems.append(f"section '{title}' is not one of {', '.join(k + ' Requirements' for k in KINDS)}")
        elif kind == "RENAMED":
            d.renamed += [(a, b) for a, b in _RENAME.findall(chunk)]
            if chunk.strip() and not _RENAME.search(chunk):
                d.problems.append("RENAMED Requirements must list lines of the form - `Old name` -> `New name`")
        else:
            getattr(d, kind.lower()).extend(parse_blocks(chunk))
    if not (d.added or d.modified or d.removed or d.renamed):
        d.problems.append("the delta changes nothing")
    return d


@dataclass
class Capability:
    id: str
    front: dict
    purpose: str = ""
    requirements: dict[str, Requirement] = field(default_factory=dict)


def parse_capability(cid: str, text: str) -> Capability:
    body = common.body_of(text)
    purpose = re.search(r"^##\s+Purpose\s*\n(.*?)(?=^##\s|\Z)", body, re.M | re.S)
    reqs = re.search(r"^##\s+Requirements\s*\n(.*)\Z", body, re.M | re.S)
    cap = Capability(cid, front_matter(text), (purpose.group(1).strip() if purpose else ""))
    for r in parse_blocks(reqs.group(1) if reqs else ""):
        cap.requirements[key(r.name)] = r
    return cap


def render_capability(cap: Capability) -> str:
    front = {"capability": cap.id, **{k: v for k, v in cap.front.items() if k != "capability"}}
    lines = ["---", yaml.safe_dump(front, sort_keys=False, default_flow_style=False).strip(), "---",
             f"<!-- {MARK}. Do not edit it: change behaviour through a spec delta, and the merge command writes this file. -->",
             f"# Capability: {front.get('title', cap.id)}", "", "## Purpose", cap.purpose or "Not stated.", "", "## Requirements"]
    for r in cap.requirements.values():
        lines += ["", f"### Requirement: {r.name}", r.body, "", f"Sources: {', '.join(r.sources)}"]
        for name, body in r.scenarios:
            lines += ["", f"#### Scenario: {name}", body]
    return "\n".join(lines) + "\n"


def apply(cap: Capability | None, delta: Delta, source: str) -> tuple[Capability | None, list[str]]:
    """Apply one delta. Returns the capability after it and the reasons it could not be applied cleanly."""
    problems = list(delta.problems)
    if cap is None:
        missing = [f for f in ("title", "owner_role", "purpose") if not str(delta.front.get(f) or "").strip()]
        if missing:
            return None, problems + [f"capability {delta.capability} is new, so the delta's front matter must give {', '.join(missing)}"]
        if delta.modified or delta.removed or delta.renamed:
            problems.append(f"capability {delta.capability} does not exist yet, so the delta can only add requirements")
        cap = Capability(delta.capability, {"title": str(delta.front["title"]), "owner_role": str(delta.front["owner_role"]),
                                            "nodes": [], "status": "active"}, str(delta.front["purpose"]).strip())
    else:
        cap = Capability(cap.id, dict(cap.front), cap.purpose, dict(cap.requirements))
    if delta.front.get("nodes"):
        cap.front["nodes"] = sorted({str(n) for n in (cap.front.get("nodes") or [])} | {str(n) for n in delta.front["nodes"]})
    if delta.front.get("status") in ("active", "retired"):
        cap.front["status"] = delta.front["status"]
    for old, new in delta.renamed:
        if key(old) not in cap.requirements:
            problems.append(f"renames '{old}', which {cap.id} does not have")
        elif key(new) in cap.requirements:
            problems.append(f"renames '{old}' to '{new}', which {cap.id} already has")
        else:
            cap.requirements = {(key(new) if k == key(old) else k): (Requirement(new, r.body, r.scenarios, [], "", r.sources + ([source] if source not in r.sources else []))
                                                                    if k == key(old) else r) for k, r in cap.requirements.items()}
    for r in delta.removed:
        if cap.requirements.pop(key(r.name), None) is None:
            problems.append(f"removes '{r.name}', which {cap.id} does not have")
    for r in delta.modified:
        old = cap.requirements.get(key(r.name))
        if old is None:
            problems.append(f"modifies '{r.name}', which {cap.id} does not have; add it under ADDED Requirements")
        else:
            cap.requirements[key(r.name)] = Requirement(r.name, r.body, list(r.scenarios), [], "", old.sources + ([source] if source not in old.sources else []))
    for r in delta.added:
        if key(r.name) in cap.requirements:
            problems.append(f"adds '{r.name}', which {cap.id} already has; change it under MODIFIED Requirements")
        else:
            cap.requirements[key(r.name)] = Requirement(r.name, r.body, list(r.scenarios), [], "", [source])
    return cap, problems


# ── reading the repository ──────────────────────────────────────────────────────

def cap_path(cid: str) -> str:
    return f"{CAPS}/{cid}/spec.md"


def capabilities(ctx: Context) -> dict[str, Capability]:
    out = {}
    for rel in ctx.src.files(CAPS):
        if rel.endswith("/spec.md") and rel.count("/") == CAPS.count("/") + 2:
            cid = rel.split("/")[-2]
            out[cid] = parse_capability(cid, ctx.src.read(rel))
    return out


def spec_deltas(ctx: Context, spec: str) -> list[Delta]:
    return [parse_delta(rel, ctx.src.read(rel)) for rel in ctx.src.files(f"specs/{spec}/deltas") if rel.endswith(".md")]


def merge_record(ctx: Context, mid: str) -> dict | None:
    rel = f"{MERGES}/{mid}.yml"
    data = ctx.src.yaml(rel) if ctx.src.exists(rel) else None
    return data if isinstance(data, dict) else None


def replay(ctx: Context) -> tuple[dict[str, str], list[tuple[str, str]]]:
    """Rebuild every living spec from the merged deltas, in order. Returns (capability id -> text, [(problem, path)])."""
    caps: dict[str, Capability] = {}
    problems: list[tuple[str, str]] = []
    for mid in common.merged(ctx):
        rec = merge_record(ctx, mid)
        rel = f"{MERGES}/{mid}.yml"
        if rec is None:
            problems.append((f"the index lists merge {mid}, which has no record", INDEX))
            continue
        for drel, digest in (rec.get("deltas") or {}).items():
            if not ctx.src.exists(drel):
                problems.append((f"merged delta {drel} no longer exists", rel))
                continue
            text = ctx.src.read(drel)
            if sha(text) != digest:
                problems.append((f"{drel} changed after it was merged; a merged delta is history", rel))
            delta = parse_delta(drel, text)
            cap, errs = apply(caps.get(delta.capability), delta, mid)
            problems += [(f"{drel}: {e}", rel) for e in errs]
            if cap is not None:
                caps[delta.capability] = cap
    return {cid: render_capability(cap) for cid, cap in caps.items()}, problems


# ── merging ─────────────────────────────────────────────────────────────────────

def plan_merge(ctx: Context, mid: str, delta_files: list[str], extra: dict) -> tuple[dict[str, str], dict, list[str]]:
    """What merging `delta_files` would write: (path -> text, the merge record, problems)."""
    caps = capabilities(ctx)
    problems, result, hashes = [], {}, {}
    for drel in sorted(delta_files):
        text = ctx.src.read(drel)
        delta = parse_delta(drel, text)
        before = caps.get(delta.capability)
        cap, errs = apply(before, delta, mid)
        problems += [f"{drel}: {e}" for e in errs]
        if cap is None:
            continue
        caps[delta.capability] = cap
        hashes[drel] = sha(text)
        result.setdefault(delta.capability, {"added": [], "modified": [], "removed": [], "renamed": []})
        result[delta.capability]["added"] += [r.name for r in delta.added]
        result[delta.capability]["modified"] += [r.name for r in delta.modified]
        result[delta.capability]["removed"] += [r.name for r in delta.removed]
        result[delta.capability]["renamed"] += [f"{a} -> {b}" for a, b in delta.renamed]
    files = {cap_path(cid): render_capability(caps[cid]) for cid in result}
    record = {"schema": MERGE_SCHEMA, "spec": mid, "merged_on": today(ctx).isoformat(), "deltas": hashes, "result": result, **extra}
    return files, record, problems


def merge(ctx: Context, spec: str | None, approved_by: dict | None = None, write: bool = False) -> tuple[list[str], dict]:
    """Merge a released spec's deltas, or (spec None) the adoption deltas, into the living specs."""
    idx = common.index(ctx)
    if idx is None:
        raise KitError(f"{INDEX} is missing; run `product init` first")
    if spec is None:
        mid, files, extra = ADOPTION_ID, [r for r in ctx.src.files(ADOPTION) if r.endswith(".md")], {"adoption": True, "approved_by": approved_by or {}}
        if not approved_by:
            raise KitError("an adoption merge needs --approved-by reviewer:role:pull/<n>#review-<id>: a named person accepts that this is what the system does today")
    else:
        mid, files, extra = spec, [d.rel for d in spec_deltas(ctx, spec)], {}
        if not complete(ctx, spec):
            raise KitError(f"{spec} has not passed every gate it needs; a delta is merged when the change is released, not before")
    if mid in common.merged(ctx):
        raise KitError(f"{mid} is already merged")
    if not files:
        raise KitError(f"there are no deltas to merge for {mid}")
    out, record, problems = plan_merge(ctx, mid, files, extra)
    if problems:
        raise KitError("the deltas do not apply: " + "; ".join(problems))
    out[f"{MERGES}/{mid}.yml"] = yaml.safe_dump(record, sort_keys=False)
    idx["order"] = common.merged(ctx) + [mid]
    out[INDEX] = yaml.safe_dump(idx, sort_keys=False)
    if write:
        for rel, text in out.items():
            path = ctx.src.root / rel
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(text, encoding="utf-8", newline="\n")
    return sorted(out), record


def seal(ctx: Context, spec: str, write: bool = False) -> dict:
    if spec not in common.merged(ctx):
        raise KitError(f"{spec} is not merged; merge its deltas before sealing it")
    base = f"specs/{spec}"
    files = {rel[len(base) + 1:]: common.sha_bytes(ctx.src.read_bytes(rel))
             for rel in ctx.src.files(base) if rel[len(base) + 1:] not in (SEAL, *AFTER_SEAL)}
    record = {"schema": SEAL_SCHEMA, "spec": spec, "sealed_on": today(ctx).isoformat(), "files": dict(sorted(files.items()))}
    if write:
        (ctx.src.root / base / SEAL).write_text(yaml.safe_dump(record, sort_keys=False), encoding="utf-8", newline="\n")
    return record


def sealed(ctx: Context, spec: str) -> bool:
    return ctx.src.exists(f"specs/{spec}/{SEAL}")


def completed_on(ctx: Context, spec: str) -> datetime.date | None:
    """The day the spec's last decision was recorded, from the audit log."""
    rel = f"{KIT_DIR}/audit/{spec}.jsonl"
    if not ctx.src.exists(rel):
        return None
    last = None
    for line in ctx.src.read(rel).splitlines():
        try:
            entry = json.loads(line)
        except ValueError:
            continue
        if str(entry.get("action", "")).startswith("gate."):
            last = as_date(str(entry.get("at", ""))[:10]) or last
    return last


# ── checks ──────────────────────────────────────────────────────────────────────

@check("CK-LIVING-SPEC", ("PRD-8", "PRD-9", "PRD-16"), "every living capability spec equals the replay of the deltas that were merged into it")
def ck_living_spec(ctx: Context, res: Result) -> None:
    present = {cap_path(cid) for cid in capabilities(ctx)}
    idx = common.index(ctx)
    if idx is None:
        if present:
            res.fail(f"capability specs exist but {INDEX} does not; run `product init`", CAPS)
        else:
            res.notes.append("living specs are not in use in this repository")
        return
    order = common.merged(ctx)
    if len(order) != len(set(order)):
        res.fail("the index lists a merge twice", INDEX)
    for mid in order:
        rec, rel = merge_record(ctx, mid), f"{MERGES}/{mid}.yml"
        if rec is None:
            continue  # reported by the replay below
        if rec.get("schema") != MERGE_SCHEMA or str(rec.get("spec")) != mid:
            res.fail(f"the record must have schema {MERGE_SCHEMA} and spec {mid}", rel)
        if rec.get("adoption"):
            by = rec.get("approved_by") or {}
            problem = decided_by_problem(ctx, by)
            if problem:
                res.fail(f"the adoption merge {problem}", rel)
            if not _REVIEW.fullmatch(str(by.get("review_ref", ""))):
                res.fail("the adoption merge names no review (approved_by.review_ref: pull/<n>#review-<id>)", rel)
        elif not ctx.src.exists(f"specs/{mid}/spec.md"):
            res.fail(f"spec {mid} does not exist", rel)
        elif not complete(ctx, mid):
            res.fail(f"{mid} was merged into the living specs before it passed every gate it needs", rel)
    expected, problems = replay(ctx)
    for message, rel in problems:
        res.fail(message, rel)
    for cid, text in expected.items():
        rel = cap_path(cid)
        if not ctx.src.exists(rel):
            res.fail("the living spec is missing; run the merge command again", rel)
        elif ctx.src.read(rel) != text:
            res.fail("the living spec differs from what its merged deltas produce. It was edited by hand, or a merge was not recorded; "
                     "change behaviour through a spec delta", rel)
    for rel in sorted(present - {cap_path(c) for c in expected}):
        res.fail("this capability spec comes from no merged delta", rel)


def _living_or_none(ctx: Context, res: Result) -> dict[str, Capability] | None:
    if common.index(ctx) is None:
        res.notes.append("living specs are not in use in this repository")
        return None
    return capabilities(ctx)


@check("CK-DELTA-VALID", ("PRD-6", "PRD-7"), "a change's deltas apply cleanly to the living specs, are testable, and cover every requirement the spec adds")
def ck_delta_valid(ctx: Context, res: Result) -> None:
    caps = _living_or_none(ctx, res)
    if caps is None:
        return
    done = set(common.merged(ctx))
    for spec in common.in_scope(ctx):
        if spec in done:
            continue
        deltas = spec_deltas(ctx, spec)
        frs = common.requirements(ctx, spec)
        covered: set[str] = set()
        seen: dict[str, str] = {}
        for d in deltas:
            if d.capability in seen:
                res.fail(f"capability {d.capability} has two deltas in this spec ({seen[d.capability]}); keep one file per capability", d.rel)
            seen[d.capability] = d.rel
            _, errs = apply(caps.get(d.capability), d, spec)
            for e in errs:
                res.fail(e, d.rel)
            owner = d.front.get("owner_role")
            if owner and str(owner) not in (ctx.roles().get("roles") or {}):
                res.fail(f"owner_role {owner} is not a role in roles.yml", d.rel)
            for r in d.added + d.modified:
                if not _NORMATIVE.search(r.body):
                    res.fail(f"requirement '{r.name}' does not say SHALL or MUST, so it is not a requirement", d.rel)
                if not r.scenarios:
                    res.fail(f"requirement '{r.name}' has no scenario, so nothing can show it works", d.rel)
                for name, body in r.scenarios:
                    low = body.lower()
                    if "when" not in low or "then" not in low:
                        res.fail(f"scenario '{name}' of '{r.name}' needs a WHEN and a THEN", d.rel)
                for fr in r.verifies:
                    if fr not in frs:
                        res.fail(f"requirement '{r.name}' verifies {fr}, which the spec does not have", d.rel)
                covered |= set(r.verifies)
            for r in d.removed:
                if not r.reason:
                    res.fail(f"'{r.name}' is removed with no `Reason:` line", d.rel)
        if deltas:
            for fr in sorted(set(frs) - covered):
                res.fail(f"{fr} is in the spec but no delta requirement says `Verifies: {fr}`, so the living spec would not show it", f"specs/{spec}/spec.md")


@check("CK-CAPABILITY-COVERAGE", ("PRD-10",), "every change says how behaviour changes, and each component it touches is described by a capability")
def ck_capability_coverage(ctx: Context, res: Result) -> None:
    caps = _living_or_none(ctx, res)
    if caps is None:
        return
    try:
        from agentic_kit_system.mapmodel import load_map
        smap = load_map(ctx, required=False)
    except ImportError:
        smap = None
    done = set(common.merged(ctx))
    described = {str(n) for c in caps.values() for n in (c.front.get("nodes") or [])}
    for spec in common.in_scope(ctx):
        if spec in done:
            continue
        rel = f"specs/{spec}/spec.md"
        front = common.front(ctx, spec)
        deltas = spec_deltas(ctx, spec)
        if front.get("behaviour") == "none":
            if not str(front.get("behaviour_reason") or "").strip():
                res.fail("`behaviour: none` needs `behaviour_reason:` saying why nothing a user can observe changes", rel)
            if deltas:
                res.fail("the spec says `behaviour: none` but carries deltas; remove one or the other", rel)
            continue
        if not deltas:
            res.fail(f"the spec carries no delta under specs/{spec}/deltas/. Say how behaviour changes, or declare `behaviour: none` with a reason", rel)
            continue
        if smap is None:
            continue
        here = described | {str(n) for d in deltas for n in (d.front.get("nodes") or [])}
        for node in [str(t) for t in (front.get("touches") or [])]:
            if (smap.nodes.get(node) or {}).get("type") in BEHAVIOUR_NODES and node not in here:
                res.fail(f"the change touches {node}, which no capability describes. Name it under `nodes:` in the delta of the capability it serves, "
                         "so coverage of the existing system grows with each change", rel)


@check("CK-DELTA-MERGED", ("PRD-9",), "a released change's deltas are merged into the living specs within the agreed number of days")
def ck_delta_merged(ctx: Context, res: Result) -> None:
    if _living_or_none(ctx, res) is None:
        return
    days = int(common.cfg(ctx).get("merge_days", 7))
    done = set(common.merged(ctx))
    for spec in common.in_scope(ctx):
        if spec in done or not spec_deltas(ctx, spec) or not complete(ctx, spec):
            continue
        finished = completed_on(ctx, spec)
        if finished is None or (today(ctx) - finished).days > days:
            when = f"on {finished}" if finished else "at a time the audit log does not record"
            res.fail(f"{spec} passed its last gate {when} and its deltas are not merged; the living specs no longer say what the system does. "
                     f"Run `product merge --spec {spec} --write`", f"specs/{spec}/spec.md")


@check("CK-SPEC-COLLISION", ("PRD-11",), "two changes in flight that alter the same requirement say which goes first")
def ck_spec_collision(ctx: Context, res: Result) -> None:
    if _living_or_none(ctx, res) is None:
        return
    done = set(common.merged(ctx))
    claims: dict[tuple[str, str], set[str]] = {}
    after: dict[str, set[str]] = {}
    for spec in common.in_scope(ctx):
        if spec in done:
            continue
        after[spec] = {str(x) for x in (common.front(ctx, spec).get("after") or [])}
        for d in spec_deltas(ctx, spec):
            names = [r.name for r in d.added + d.modified + d.removed] + [a for a, _ in d.renamed]
            for name in names:
                claims.setdefault((d.capability, key(name)), set()).add(spec)
    reported = set()
    for (cap, name), specs in sorted(claims.items()):
        for a in sorted(specs):
            for b in sorted(specs):
                if a < b and b not in after[a] and a not in after[b] and (a, b, cap, name) not in reported:
                    reported.add((a, b, cap, name))
                    res.fail(f"{a} and {b} both change requirement '{name}' of {cap}. One must list the other under `after:` in its front matter, "
                             "so the second is written against the first", f"specs/{b}/spec.md")


@check("CK-ARCHIVE", ("PRD-12", "PRD-13"), "a merged change is sealed, and a sealed change never changes")
def ck_archive(ctx: Context, res: Result) -> None:
    if _living_or_none(ctx, res) is None:
        return
    days = int(common.cfg(ctx).get("archive_days", 30))
    for mid in common.merged(ctx):
        rec = merge_record(ctx, mid) or {}
        if rec.get("adoption"):
            continue
        base = f"specs/{mid}"
        rel = f"{base}/{SEAL}"
        if not ctx.src.exists(rel):
            merged_on = as_date(rec.get("merged_on"))
            if merged_on is None or (today(ctx) - merged_on).days > days:
                res.fail(f"{mid} was merged on {merged_on or 'an unrecorded date'} and is not sealed; run `product archive --spec {mid} --write`. "
                         "An unsealed finished spec is stale text an agent may read as current", f"{base}/spec.md")
            continue
        seal_rec = ctx.src.yaml(rel) or {}
        files = seal_rec.get("files") or {}
        if seal_rec.get("schema") != SEAL_SCHEMA or not files:
            res.fail(f"the seal must have schema {SEAL_SCHEMA} and list files", rel)
            continue
        for name, digest in files.items():
            if not ctx.src.exists(f"{base}/{name}"):
                res.fail(f"sealed file {name} was removed", rel)
            elif common.sha_bytes(ctx.src.read_bytes(f"{base}/{name}")) != digest:
                res.fail(f"sealed file {name} changed after the spec was sealed; a finished change is history. Open a new spec", rel)
        for present in ctx.src.files(base):
            name = present[len(base) + 1:]
            if name not in files and name not in (SEAL, *AFTER_SEAL):
                res.fail(f"{name} was added after the spec was sealed", rel)
